namespace Motivators.Domain;

public record MotivatorCard(
    string Key,
    string Name,
    string EnglishName,
    string Statement,
    string AccentColor,
    IReadOnlyList<string> DiscussionPrompts);

public record HealthCheckCategory(
    string Key,
    string Name,
    string Awesome,
    string Awful,
    IReadOnlyList<string> DiscussionPrompts);

public record MethodologyVersionContent(
    int Version,
    IReadOnlyList<MotivatorCard> Motivators,
    IReadOnlyList<HealthCheckCategory> HealthCheckCategories)
{
    public MotivatorCard? FindMotivator(string key) => Motivators.FirstOrDefault(m => m.Key == key);
    public HealthCheckCategory? FindCategory(string key) => HealthCheckCategories.FirstOrDefault(c => c.Key == key);
}

